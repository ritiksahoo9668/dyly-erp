EMPLOYEE_EXCEL_HEADERS = [
    "Full Name",
    "Department",
    "Vertical",
    "Personal Email",
    "Company Email",
    "Designation",
    "Company",
    "Division",
    "Facility",
    "Date Of Joining",
    "Location",
    "Gender",
    "Mobile Number",
]
EMPLOYEE_HEADER_KEYS = [_normalize_header(h) for h in EMPLOYEE_EXCEL_HEADERS]
LABEL_BY_KEY = dict(zip(EMPLOYEE_HEADER_KEYS, EMPLOYEE_EXCEL_HEADERS, strict=True))

REQUIRED_KEYS = [
    "full name",
    "department",
    "designation",
    "company",
    "date of joining",
    "location",
    "gender",
    "mobile number",
]
RAW_KEYS = {"date of joining", "mobile number"}
TEMPLATE_FORMATTED_ROWS = 1000
POSSIBLE_DUPLICATE_PREFIX = "Possible Duplicate"
PREVIEW_ROW_LIMIT = 500


def build_employee_template() -> BytesIO:
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Employees"
    for col, header in enumerate(EMPLOYEE_EXCEL_HEADERS, start=1):
        sheet.cell(1, col, header)
        sheet.column_dimensions[sheet.cell(1, col).column_letter].width = max(16, len(header) + 4)

    mobile_col = EMPLOYEE_HEADER_KEYS.index("mobile number") + 1
    date_col = EMPLOYEE_HEADER_KEYS.index("date of joining") + 1
    gender_col = EMPLOYEE_HEADER_KEYS.index("gender") + 1
    for row in range(2, TEMPLATE_FORMATTED_ROWS + 2):
        sheet.cell(row, mobile_col).number_format = "@"
        sheet.cell(row, date_col).number_format = "DD-MM-YYYY"

    gender_letter = sheet.cell(1, gender_col).column_letter
    gender_list = ",".join(label for _, label in Employee.Gender.choices)
    validation = DataValidation(type="list", formula1=f'"{gender_list}"', allow_blank=True)
    validation.add(f"{gender_letter}2:{gender_letter}{TEMPLATE_FORMATTED_ROWS + 1}")
    sheet.add_data_validation(validation)
    sheet.freeze_panes = "A2"

    instructions = workbook.create_sheet("Instructions")
    lines = [
        "Instructions",
        "Use the 13 column headers exactly as provided. Do not rename or remove headers.",
        "Mandatory: Full Name, Department, Designation, Company, Date Of Joining, "
        "Location, Gender, Mobile Number.",
        "Optional: Vertical, Personal Email, Company Email, Division, Facility.",
        "Employee Code is generated by the system. Do not add Employee Code or Is Active columns.",
        "Imported Employees are created as Active automatically.",
        "Department, Vertical, Designation, Company, Division and Facility must already "
        "exist in their Masters (matched ignoring case). Missing Masters are not created.",
        "Vertical must belong to the selected Department.",
        f"Gender: {GENDER_CHOICES_TEXT} (M and F are accepted).",
        "Date Of Joining: an Excel date, or DD-MM-YYYY / DD/MM/YYYY / YYYY-MM-DD.",
        "Mobile Number: format the column as Text. 10 to 15 digits; a leading + country code "
        "is kept (for example +919876543210).",
        "An existing Mobile Number is skipped. Rows whose Personal Email, or Company Email + "
        "Full Name, match an existing Employee are held back as Possible Duplicate for review.",
        "",
        "Example row:",
    ]
    for index, text in enumerate(lines, start=1):
        instructions.cell(index, 1, text)
    example_row = len(lines) + 1
    example = [
        "Ravi Kumar",
        "Purchase",
        "",
        "ravi.kumar@gmail.com",
        "ravi.kumar@company.com",
        "Manager",
        "De-Maithan Ispat Limited",
        "",
        "",
        "01-04-2026",
        "Jajpur",
        "Male",
        "+919876543210",
    ]
    for col, header in enumerate(EMPLOYEE_EXCEL_HEADERS, start=1):
        instructions.cell(example_row, col, header)
        instructions.cell(example_row + 1, col, example[col - 1])

    buffer = BytesIO()
    workbook.save(buffer)
    buffer.seek(0)
    return buffer


def _header_index(header_row) -> dict[str, int]:
    header = [_normalize_header(cell) for cell in (header_row or ())]
    for key in EMPLOYEE_HEADER_KEYS:
        if key not in header:
            raise ValueError(INVALID_TEMPLATE_MESSAGE)
    return {key: header.index(key) for key in EMPLOYEE_HEADER_KEYS}


def validate_employee_template(file_obj) -> None:
    workbook = load_workbook(file_obj, read_only=True, data_only=True)
    rows = workbook.active.iter_rows(values_only=True)
    try:
        header_row = next(rows)
    except StopIteration as exc:
        raise ValueError("Excel file is empty.") from exc
    _header_index(header_row)


def _is_blank(value) -> bool:
    return value is None or (isinstance(value, str) and not value.strip())


def iter_employee_excel_rows(file_obj):
    """Yield (row_number, data) for non-blank rows. Date and mobile cells keep their raw type."""
    workbook = load_workbook(file_obj, read_only=True, data_only=True)
    rows = workbook.active.iter_rows(values_only=True)
    try:
        header_row = next(rows)
    except StopIteration as exc:
        raise ValueError("Excel file is empty.") from exc
    idx_map = _header_index(header_row)
    for row_number, row in enumerate(rows, start=2):
        values = list(row or ())
        data: dict = {}
        for key, idx in idx_map.items():
            raw = values[idx] if idx < len(values) else None
            if key in RAW_KEYS:
                data[key] = clean_text(raw) if isinstance(raw, str) else raw
            else:
                data[key] = clean_text(raw)
        if all(_is_blank(value) for value in data.values()):
            continue
        yield row_number, data


def _display(value) -> str:
    if value is None:
        return ""
    if isinstance(value, datetime):
        return value.date().isoformat()
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def row_payload_for_error(data: dict) -> str:
    return json.dumps([_display(data.get(key)) for key in EMPLOYEE_HEADER_KEYS], ensure_ascii=False)


def _key(value: str) -> str:
    return clean_text(value).casefold()


class EmployeeLookupMaps:
    def __init__(self):
        self.departments = {_key(d.name): d for d in Department.objects.all()}
        self.verticals = {_key(v.name): v for v in Vertical.objects.all()}
        self.designations = {_key(d.name): d for d in Designation.objects.all()}
        self.companies = {_key(c.name): c for c in Company.objects.all()}
        self.divisions = {_key(d.name): d for d in Division.objects.all()}
        self.facilities = {_key(f.name): f for f in Facility.objects.all()}

        self.mobiles: dict[str, str] = {}
        self.file_mobiles: dict[str, str] = {}
        self.personal_emails: dict[str, str] = {}
        self.company_email_names: dict[tuple[str, str], str] = {}
        for name, designation, department, mobile, personal, company_email in (
            Employee.objects.values_list(
                "full_name",
                "designation__name",
                "department__name",
                "mobile_number",
                "personal_email",
                "company_email",
            )
        ):
            self.remember(
                name,
                mobile,
                personal,
                company_email,
                label=employee_label(name, designation, department),
            )

    def remember(
        self, name, mobile, personal, company_email, *, label: str, from_file: bool = False
    ) -> None:
        (self.file_mobiles if from_file else self.mobiles).setdefault(mobile, label)
        if personal:
            self.personal_emails.setdefault(personal, label)
        if company_email:
            self.company_email_names.setdefault((company_email, _key(name)), label)


def _lookup_master(mapping: dict, raw: str, label: str):
    record = mapping.get(_key(raw))
    if record is None:
        return None, f'{label} "{raw}" not found'
    if not record.is_active:
        return None, f'{label} "{raw}" is inactive'
    return record, None


def resolve_employee_row(data: dict, lookups: EmployeeLookupMaps, *, row_number: int):
    """Return (resolved_kwargs, error, skip_reason, possible_duplicate_reason)."""
    for key in REQUIRED_KEYS:
        if _is_blank(data.get(key)):
            return None, f"{LABEL_BY_KEY[key]} is required.", None, None

    full_name = data["full name"]
    if len(full_name) > 150:
        return None, "Full Name must be 150 characters or fewer.", None, None
    location = data["location"]
    if len(location) > 150:
        return None, "Location must be 150 characters or fewer.", None, None

    department, error = _lookup_master(lookups.departments, data["department"], "Department")
    if error:
        return None, error, None, None

    vertical = None
    if data["vertical"]:
        vertical, error = _lookup_master(lookups.verticals, data["vertical"], "Vertical")
        if error:
            return None, error, None, None
        if vertical.department_id != department.pk:
            return (
                None,
                f'Vertical "{data["vertical"]}" does not belong to Department '
                f'"{data["department"]}"',
                None,
                None,
            )

    designation, error = _lookup_master(lookups.designations, data["designation"], "Designation")
    if error:
        return None, error, None, None

    company, error = _lookup_master(lookups.companies, data["company"], "Company")
    if error:
        return None, error, None, None

    division = None
    if data["division"]:
        division, error = _lookup_master(lookups.divisions, data["division"], "Division")
        if error:
            return None, error, None, None

    facility = None
    if data["facility"]:
        facility, error = _lookup_master(lookups.facilities, data["facility"], "Facility")
        if error:
            return None, error, None, None

    personal_email, error = normalize_email(data["personal email"], label="Personal Email")
    if error:
        return None, error, None, None
    company_email, error = normalize_email(data["company email"], label="Company Email")
    if error:
        return None, error, None, None

    joining, error = parse_joining_date(data["date of joining"])
    if error:
        return None, error, None, None

    gender = normalize_gender(data["gender"])
    if gender is None:
        return (
            None,
            f'Invalid Gender "{data["gender"]}". Use {GENDER_CHOICES_TEXT}.',
            None,
            None,
        )

    mobile, error = normalize_mobile(data["mobile number"])
    if error:
        return None, error, None, None

    if mobile in lookups.file_mobiles:
        return (
            None,
            f"Duplicate Mobile Number within the Excel file ({lookups.file_mobiles[mobile]}).",
            None,
            None,
        )
    if mobile in lookups.mobiles:
        return (
            None,
            None,
            f"Skipped Existing — Mobile Number already belongs to {lookups.mobiles[mobile]}.",
            None,
        )

    resolved = {
        "full_name": full_name,
        "department": department,
        "vertical": vertical,
        "personal_email": personal_email,
        "company_email": company_email,
        "designation": designation,
        "company": company,
        "division": division,
        "facility": facility,
        "date_of_joining": joining,
        "location": location,
        "gender": gender,
        "mobile_number": mobile,
        "is_active": True,
    }

    possible = None
    if personal_email and personal_email in lookups.personal_emails:
        possible = (
            f"{POSSIBLE_DUPLICATE_PREFIX} — Personal Email matches "
            f"{lookups.personal_emails[personal_email]}."
        )
    elif company_email and (company_email, _key(full_name)) in lookups.company_email_names:
        possible = (
            f"{POSSIBLE_DUPLICATE_PREFIX} — Company Email + Full Name match "
            f"{lookups.company_email_names[(company_email, _key(full_name))]}."
        )

    lookups.remember(
        full_name,
        mobile,
        personal_email,
        company_email,
        label=f"row {row_number}",
        from_file=True,
    )
    return resolved, None, None, possible


def preview_employees_from_excel(file_obj) -> dict:
    rows = list(iter_employee_excel_rows(file_obj))
    if not rows:
        empty = _empty_preview(errors=[{"row": 1, "reason": "Excel file has no data rows."}])
        return {**empty, "possible_duplicates": 0}

    lookups = EmployeeLookupMaps()
    valid = existing = failed = possible = 0
    issues: list[dict] = []
    valid_rows: list[dict] = []

    for row_number, data in rows:
        resolved, error, skip, possible_reason = resolve_employee_row(
            data, lookups, row_number=row_number
        )
        entry = {
            "row": row_number,
            "full_name": data.get("full name", ""),
            "mobile_number": _display(data.get("mobile number")),
            "status": "valid",
            "reason": "",
        }
        if error:
            failed += 1
            entry.update(status="failed", reason=error)
        elif skip:
            existing += 1
            entry.update(status="existing", reason=skip)
        elif possible_reason:
            possible += 1
            entry.update(status="possible_duplicate", reason=possible_reason)
        elif resolved is not None:
            valid += 1
            if len(valid_rows) < PREVIEW_ROW_LIMIT:
                valid_rows.append(entry)
            continue
        if len(issues) < PREVIEW_ROW_LIMIT:
            issues.append(entry)

    preview_rows = issues + valid_rows[: max(0, PREVIEW_ROW_LIMIT - len(issues))]
    return {
        "total": len(rows),
        "valid": valid,
        "possible_duplicates": possible,
        "existing": existing,
        "duplicate": 0,
        "failed": failed,
        "rows": preview_rows,
        "errors": [
            {"row": entry["row"], "reason": entry["reason"]}
            for entry in issues
            if entry["status"] == "failed"
        ],
    }
